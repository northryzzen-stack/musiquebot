def get_txt(lang: str, key: str, **kwargs) -> str:
    if lang not in TEXTS:
        lang = "ru"

    text = TEXTS[lang].get(
        key,
        TEXTS["ru"].get(key, key)
    )

    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text

    return text

